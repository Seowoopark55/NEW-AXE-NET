-- 4. AXE BOT -> NEW Supabase 직접 승인/반려
-- =========================================================
create or replace function new_axe_net.bot_review_fund_request(
  p_request_id bigint,
  p_action text,
  p_reviewer_name text,
  p_review_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request new_axe_net.fund_requests%rowtype;
  v_action text := lower(btrim(coalesce(p_action,'')));
  v_ledger_id bigint;
  v_operation_key text;
  v_reviewer text := coalesce(nullif(btrim(p_reviewer_name),''),'AXE BOT');
begin
  perform pg_advisory_xact_lock(1380138063);

  if not exists (
    select 1 from new_axe_net.fund_runtime_config c
    where c.id = 1 and c.primary_source = 'new_axe_net'
  ) then
    raise exception '공금 최종 전환 전에는 NEW 검수를 사용할 수 없습니다.' using errcode = '55000';
  end if;

  select * into v_request
  from new_axe_net.fund_requests
  where id = p_request_id
  for update;

  if not found then raise exception '신청을 찾을 수 없습니다.' using errcode = '22023'; end if;

  if v_action in ('approve','approved','승인') then
    if v_request.status = 'approved' then
      select l.id into v_ledger_id from new_axe_net.fund_ledger l
      where l.request_id=p_request_id and l.status='active' order by l.id desc limit 1;
      return jsonb_build_object('success',true,'idempotent',true,'status','approved','ledger_id',v_ledger_id);
    end if;
    if v_request.status not in ('pending','hold') then
      raise exception '이미 처리된 신청입니다.' using errcode = '22023';
    end if;
    if exists (
      select 1 from new_axe_net.fund_ledger l
      where l.member_key=v_request.member_key and l.year=v_request.year and l.month=v_request.month and l.week=v_request.week
        and l.entry_type='payment' and l.status='active'
    ) then
      raise exception '이미 해당 주차에 활성 납부 기록이 있습니다.' using errcode = '23505';
    end if;

    v_operation_key := new_axe_net.new_fund_operation_key('discord_bot_approved');
    insert into new_axe_net.fund_ledger (
      legacy_id, member_key, nickname, year, month, week,
      entry_type, amount, public_amount, company_amount, status,
      approved_by_name, approved_at, legacy_request_key, source_key,
      memo, ledger_date, ledger_type, category, direction, account,
      evidence_url, operation_key, request_id
    ) values (
      null,v_request.member_key,v_request.nickname,v_request.year,v_request.month,v_request.week,
      'payment',v_request.amount,v_request.public_amount,v_request.company_amount,'active',
      v_reviewer,now(),'new_request:'||v_request.id::text,v_operation_key,
      concat_ws(' · ', nullif(v_request.memo,''), nullif(p_review_note,'')),
      now(),'공금납부','주간공금','수입',coalesce(v_request.payment_mode,'공용계좌'),
      v_request.evidence_url,v_operation_key,v_request.id
    ) returning id into v_ledger_id;

    update new_axe_net.fund_requests set
      status='approved', reviewer_discord_name=v_reviewer, reviewed_at=now(),
      review_note=nullif(btrim(p_review_note),'')
    where id=p_request_id;

    return jsonb_build_object('success',true,'status','approved','ledger_id',v_ledger_id);
  elsif v_action in ('reject','rejected','반려','거절') then
    if v_request.status = 'rejected' then
      return jsonb_build_object('success',true,'idempotent',true,'status','rejected');
    end if;
    if v_request.status not in ('pending','hold') then
      raise exception '이미 처리된 신청입니다.' using errcode = '22023';
    end if;
    update new_axe_net.fund_requests set
      status='rejected', reviewer_discord_name=v_reviewer, reviewed_at=now(),
      review_note=nullif(btrim(p_review_note),'')
    where id=p_request_id;
    return jsonb_build_object('success',true,'status','rejected');
  else
    raise exception 'action은 승인 또는 반려여야 합니다.' using errcode = '22023';
  end if;
end;
$$;

