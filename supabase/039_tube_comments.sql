on new_axe_net.tube_comments
for select to anon, authenticated
using (
  active = true
  and exists (
    select 1
    from new_axe_net.tube_videos v
    where v.tube_id = tube_comments.tube_id
      and v.active = true
  )
);

create or replace function new_axe_net.sync_tube_comment_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_tube_id text;
  v_new_tube_id text;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_old_tube_id := old.tube_id;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    v_new_tube_id := new.tube_id;
  end if;

  if v_old_tube_id is not null then
    update new_axe_net.tube_videos v
    set comment_count = (
      select count(*)::integer
      from new_axe_net.tube_comments c
      where c.tube_id = v_old_tube_id
        and c.active = true
    )
    where v.tube_id = v_old_tube_id;
  end if;

  if v_new_tube_id is not null
     and v_new_tube_id is distinct from v_old_tube_id then
    update new_axe_net.tube_videos v
    set comment_count = (
      select count(*)::integer
      from new_axe_net.tube_comments c
      where c.tube_id = v_new_tube_id
        and c.active = true
    )
    where v.tube_id = v_new_tube_id;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists tube_comments_sync_count
