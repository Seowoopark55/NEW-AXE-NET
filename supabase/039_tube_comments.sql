alter table new_axe_net.tube_videos
  add column if not exists comment_count integer not null default 0;

alter table new_axe_net.tube_videos
  drop constraint if exists tube_videos_comment_count_check;

alter table new_axe_net.tube_videos
  add constraint tube_videos_comment_count_check
  check (comment_count >= 0);

create table if not exists new_axe_net.tube_comments (
  id bigint generated by default as identity primary key,
  tube_id text not null
    references new_axe_net.tube_videos(tube_id)
    on update cascade on delete cascade,
  member_key text not null
    references new_axe_net.members(member_key)
    on update cascade on delete restrict,
  author_name text not null,
  author_badge text,
  body text not null,
  edited_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tube_comments_body_length_check
    check (char_length(btrim(body)) between 1 and 500)
);

create index if not exists tube_comments_tube_active_created_idx
  on new_axe_net.tube_comments(tube_id, active, created_at asc);

create index if not exists tube_comments_member_idx
  on new_axe_net.tube_comments(member_key, updated_at desc);

