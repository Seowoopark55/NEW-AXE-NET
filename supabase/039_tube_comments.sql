  select count(*)::integer
  from new_axe_net.tube_comments c
  where c.tube_id = v.tube_id
    and c.active = true
);

create or replace function new_axe_net.deactivate_tube_comment_admin(
  p_comment_id bigint
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.'
      using errcode = '42501';
  end if;

  update new_axe_net.tube_comments
  set
    active = false,
    updated_at = now()
  where id = p_comment_id
    and active = true;

  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;

revoke all
on function new_axe_net.deactivate_tube_comment_admin(bigint)
from public, anon;

grant execute
on function new_axe_net.deactivate_tube_comment_admin(bigint)
to authenticated;

notify pgrst, 'reload schema';

