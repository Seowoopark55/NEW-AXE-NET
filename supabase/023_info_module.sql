create table if not exists new_axe_net.info_crafts (
  id text primary key,
  category text not null,
  item_name text not null,
  success_rate integer,
  craft_rank text,
  obtain_place text,
  note text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (success_rate is null or (success_rate between 0 and 100)),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_craft_materials (
  id bigint generated by default as identity primary key,
  legacy_key text not null unique,
  craft_id text not null references new_axe_net.info_crafts(id) on delete cascade,
  material_name text not null,
  quantity numeric(12,2) not null default 0,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (quantity >= 0),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_material_recipes (
  id bigint generated by default as identity primary key,
  legacy_key text not null unique,
  item_name text not null,
  input1 text,
  input1_qty numeric(12,2) not null default 0,
  input2 text,
  input2_qty numeric(12,2) not null default 0,
  input3 text,
  input3_qty numeric(12,2) not null default 0,
  note text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (input1_qty >= 0 and input2_qty >= 0 and input3_qty >= 0),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_quests (
  id bigint generated by default as identity primary key,
  legacy_key text not null unique,
  job text not null,
  item_name text not null,
  required_qty numeric(12,2) not null default 0,
  reward_money integer not null default 0,
  reward_xp integer,
  rank text,
  note text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (required_qty >= 0),
  check (reward_money >= 0),
  check (reward_xp is null or reward_xp >= 0),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_processes (
  id bigint generated by default as identity primary key,
  legacy_key text not null unique,
  job text not null,
  process_type text not null,
  item_name text not null,
  input1 text,
  input1_qty numeric(12,2) not null default 0,
  input2 text,
  input2_qty numeric(12,2) not null default 0,
  output_qty numeric(12,2) not null default 0,
  quest_qty numeric(12,2) not null default 0,
  reward_money integer not null default 0,
  reward_xp integer,
  rank text,
  note text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (input1_qty >= 0 and input2_qty >= 0 and output_qty >= 0 and quest_qty >= 0),
  check (reward_money >= 0 and reward_xp >= 0),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_modbooks (
  id bigint generated by default as identity primary key,
  legacy_key text unique,
  type text not null check (type in ('접두', '접미')),
  category text not null,
  name text not null,
  parts text not null default '',
  option1 text,
  option2 text,
  option3 text,
  success_rate integer,
  note text,
  sort_order integer not null default 0,
  recent_price integer,
  recent_date date,
  price_note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (success_rate is null or (success_rate between 0 and 100)),
  check (recent_price is null or recent_price >= 0),
  check (sort_order >= 0)
);

create table if not exists new_axe_net.info_skill_ranks (
  id bigint generated by default as identity primary key,
  legacy_key text not null unique,
  skill text not null,
  rank text not null,
  required_point numeric(12,2) not null default 0,
  point_type text,
  note text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (required_point >= 0),
  check (sort_order >= 0)
);

-- 개조서 등록 신청은 멤버 웹 세션을 검증한 Vercel API가 service_role로 기록합니다.
create table if not exists new_axe_net.info_modbook_requests (
  id bigint generated by default as identity primary key,
  member_key text not null references new_axe_net.members(member_key) on delete restrict,
  nickname text not null,
  type text not null check (type in ('접두', '접미')),
  category text not null,
  name text not null,
  parts text not null default '',
  option1 text,
  option2 text,
  option3 text,
  success_rate integer,
  note text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  review_note text,
  reviewer text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (success_rate is null or (success_rate between 0 and 100))
);

