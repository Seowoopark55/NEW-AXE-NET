create or replace function new_axe_net.save_info_modbook(
  p_id bigint,
  p_type text,
  p_category text,
  p_name text,
  p_parts text,
  p_option1 text,
  p_option2 text,
  p_option3 text,
  p_success_rate integer,
  p_note text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_type text := btrim(coalesce(p_type, ''));
  v_category text := nullif(btrim(coalesce(p_category, '')), '');
  v_name text := nullif(btrim(coalesce(p_name, '')), '');
  v_parts text := btrim(coalesce(p_parts, ''));
  v_order integer;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;
  if v_type not in ('접두','접미') then
    raise exception '개조 위치는 접두 또는 접미여야 합니다.' using errcode = '22023';
  end if;
  if v_category is null or v_name is null then
    raise exception '분류와 개조서 이름을 입력하세요.' using errcode = '22023';
  end if;
  if p_success_rate is not null and (p_success_rate < 0 or p_success_rate > 100) then
    raise exception '성공률은 0~100 사이로 입력하세요.' using errcode = '22023';
  end if;

  if p_id is null then
    select coalesce(max(sort_order), 0) + 1
      into v_order
    from new_axe_net.info_modbooks
    where type = v_type and category = v_category;

    insert into new_axe_net.info_modbooks (
      type, category, name, parts, option1, option2, option3,
      success_rate, note, sort_order, active
    ) values (
      v_type, v_category, v_name, v_parts,
      nullif(btrim(coalesce(p_option1,'')), ''),
      nullif(btrim(coalesce(p_option2,'')), ''),
      nullif(btrim(coalesce(p_option3,'')), ''),
      p_success_rate,
      nullif(btrim(coalesce(p_note,'')), ''),
      v_order,
      true
    ) returning id into v_id;
  else
    update new_axe_net.info_modbooks
       set type = v_type,
           category = v_category,
           name = v_name,
           parts = v_parts,
           option1 = nullif(btrim(coalesce(p_option1,'')), ''),
           option2 = nullif(btrim(coalesce(p_option2,'')), ''),
           option3 = nullif(btrim(coalesce(p_option3,'')), ''),
           success_rate = p_success_rate,
           note = nullif(btrim(coalesce(p_note,'')), ''),
           active = true
     where id = p_id
     returning id into v_id;

    if v_id is null then
      raise exception '수정할 개조서를 찾을 수 없습니다.' using errcode = 'P0002';
    end if;
  end if;

  return v_id;
end;
$$;

create or replace function new_axe_net.update_info_modbook_price(
  p_id bigint,
  p_recent_price integer,
  p_price_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_actor text;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;
  if p_recent_price is not null and p_recent_price < 0 then
    raise exception '최근 거래가는 0 이상으로 입력하세요.' using errcode = '22023';
  end if;

  v_actor := coalesce(new_axe_net.info_actor_nickname(), 'ADMIN');

  update new_axe_net.info_modbooks
     set recent_price = p_recent_price,
         recent_date = case when p_recent_price is null then null else (now() at time zone 'Asia/Seoul')::date end,
         price_note = case
           when p_recent_price is null then null
           else coalesce(nullif(btrim(coalesce(p_price_note,'')), ''), v_actor)
         end
   where id = p_id and active = true
   returning id into v_id;

  if v_id is null then
    raise exception '개조서를 찾을 수 없습니다.' using errcode = 'P0002';
  end if;
  return v_id;
end;
$$;

create or replace function new_axe_net.deactivate_info_modbook(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;

  update new_axe_net.info_modbooks
     set active = false
   where id = p_id and active = true;
  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;

