create or replace function new_axe_net.review_info_modbook_request(
  p_request_id bigint,
  p_action text,
  p_review_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request new_axe_net.info_modbook_requests%rowtype;
  v_action text := lower(btrim(coalesce(p_action,'')));
  v_actor text;
  v_modbook_id bigint := null;
  v_order integer;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;
  if v_action not in ('approve','reject') then
    raise exception '승인 또는 반려 작업만 지원합니다.' using errcode = '22023';
  end if;

  select * into v_request
  from new_axe_net.info_modbook_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception '신청 내역을 찾을 수 없습니다.' using errcode = 'P0002';
  end if;
  if v_request.status <> 'pending' then
    raise exception '이미 처리된 신청입니다.' using errcode = '22023';
  end if;

  v_actor := coalesce(new_axe_net.info_actor_nickname(), 'ADMIN');

  if v_action = 'approve' then
    select coalesce(max(sort_order), 0) + 1
      into v_order
    from new_axe_net.info_modbooks
    where type = v_request.type and category = v_request.category;

    insert into new_axe_net.info_modbooks (
      type, category, name, parts, option1, option2, option3,
      success_rate, note, sort_order, active
    ) values (
      v_request.type, v_request.category, v_request.name, v_request.parts,
      v_request.option1, v_request.option2, v_request.option3,
      v_request.success_rate, v_request.note, v_order, true
    ) returning id into v_modbook_id;

    update new_axe_net.info_modbook_requests
       set status = 'approved',
           review_note = nullif(btrim(coalesce(p_review_note,'')), ''),
           reviewer = v_actor,
           reviewed_at = now()
     where id = p_request_id;
  else
    update new_axe_net.info_modbook_requests
       set status = 'rejected',
           review_note = nullif(btrim(coalesce(p_review_note,'')), ''),
           reviewer = v_actor,
           reviewed_at = now()
     where id = p_request_id;
  end if;

  return coalesce(v_modbook_id, p_request_id);
end;
$$;

