-- updated_at은 기존 공통 함수 사용
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'info_crafts','info_craft_materials','info_material_recipes','info_quests',
    'info_processes','info_modbooks','info_skill_ranks','info_modbook_requests'
  ] LOOP
    EXECUTE format('drop trigger if exists %I on new_axe_net.%I', t || '_touch_updated_at', t);
    EXECUTE format(
      'create trigger %I before update on new_axe_net.%I for each row execute function new_axe_net.touch_updated_at()',
      t || '_touch_updated_at', t
    );
  END LOOP;
END $$;

