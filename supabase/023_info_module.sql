create or replace function new_axe_net.info_actor_nickname()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select m.nickname
  from new_axe_net.admin_accounts a
  join new_axe_net.members m on m.member_key = a.member_key
  where a.user_id = auth.uid()
    and a.enabled = true
  limit 1;
$$;

