create table if not exists info_preset_posts (
  id bigint generated by default as identity primary key,
  system_key text unique,
  author_member_key text references members(member_key) on update cascade on delete set null,
  author_nickname text not null default 'AXE',
  title text not null,
  description text not null default '',
  tags text[] not null default '{}'::text[],
  favorite_count integer not null default 0 check (favorite_count >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint info_preset_posts_title_len check (char_length(title) between 1 and 100),
  constraint info_preset_posts_description_len check (char_length(description) <= 4000)
);

create table if not exists info_preset_post_slots (
  id bigint generated by default as identity primary key,
  post_id bigint not null references info_preset_posts(id) on delete cascade,
  slot_key text not null check (slot_key in ('outer','top','bottom','shoes')),
  prefix_modbook_id bigint references info_modbooks(id) on delete set null,
  suffix_modbook_id bigint references info_modbooks(id) on delete set null,
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (post_id, slot_key),
  constraint info_preset_post_slots_note_len check (char_length(note) <= 500)
);

create table if not exists member_preset_favorites (
  member_key text not null references members(member_key) on update cascade on delete cascade,
  post_id bigint not null references info_preset_posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (member_key, post_id)
);

create index if not exists info_preset_posts_active_updated_idx
  on info_preset_posts (active, updated_at desc, id desc);
create index if not exists info_preset_post_slots_post_idx
  on info_preset_post_slots (post_id, slot_key);
create index if not exists member_preset_favorites_post_idx
  on member_preset_favorites (post_id);

alter table info_preset_posts enable row level security;
alter table info_preset_post_slots enable row level security;
alter table member_preset_favorites enable row level security;

drop policy if exists info_preset_posts_public_read on info_preset_posts;
create policy info_preset_posts_public_read
  on info_preset_posts for select
  using (active = true);

drop policy if exists info_preset_post_slots_public_read on info_preset_post_slots;
create policy info_preset_post_slots_public_read
  on info_preset_post_slots for select
  using (
    exists (
      select 1
      from info_preset_posts p
      where p.id = info_preset_post_slots.post_id
        and p.active = true
    )
  );

-- 즐겨찾기는 커스텀 멤버 세션 API(service role)에서만 접근합니다.
