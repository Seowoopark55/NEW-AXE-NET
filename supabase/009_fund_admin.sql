create or replace function new_axe_net.create_fund_fee_rule(
  p_start_year integer,
  p_start_month integer,
  p_start_week integer,
  p_weekly_fee integer,
  p_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_actor text;
  v_source_key text;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.'
      using errcode = '42501';
  end if;

  if new_axe_net.fund_period_end(
    p_start_year,
    p_start_month,
    p_start_week
  ) is null then
    raise exception '존재하지 않는 공금 주차입니다.'
      using errcode = '22023';
  end if;

  if p_weekly_fee is null or p_weekly_fee < 0 then
    raise exception '주간 공금은 0원 이상의 정수여야 합니다.'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from new_axe_net.fund_fee_rules r
    where r.start_year = p_start_year
      and r.start_month = p_start_month
      and r.start_week = p_start_week
      and r.enabled = true
  ) then
    raise exception '해당 적용 시점에 이미 활성 회비 규칙이 있습니다.'
      using errcode = '23505';
  end if;

  v_actor := coalesce(
    new_axe_net.fund_actor_nickname(),
    'unknown'
  );

  v_source_key :=
    'new_fund_fee:' ||
    floor(extract(epoch from clock_timestamp()) * 1000)::bigint::text ||
    ':' ||
    substr(
      md5(
        random()::text ||
        p_start_year::text ||
        p_start_month::text ||
        p_start_week::text ||
        clock_timestamp()::text
      ),
      1,
      10
    );

  insert into new_axe_net.fund_fee_rules (
    source_id,
    start_year,
    start_month,
    start_week,
    weekly_fee,
    note,
    enabled,
    source_key
  )
  values (
    'new_axe_net',
    p_start_year,
    p_start_month,
    p_start_week,
    p_weekly_fee,
    nullif(btrim(p_note), ''),
    true,
    v_source_key
  )
  returning id into v_id;

  insert into new_axe_net.fund_admin_audit_log (
    action,
    target_type,
    target_key,
    actor_user_id,
    actor_nickname,
    payload
  )
  values (
    'create_fee_rule',
    'fund_fee_rule',
    v_id::text,
    auth.uid(),
    v_actor,
    jsonb_build_object(
      'start_year', p_start_year,
      'start_month', p_start_month,
      'start_week', p_start_week,
      'weekly_fee', p_weekly_fee,
      'note', nullif(btrim(p_note), '')
    )
  );

  return v_id;
end;
$$;

-- --------------------------------------------------
-- 회비 규칙 활성/비활성
-- base_weekly_fee는 안전망이므로 비활성화 금지
-- --------------------------------------------------

create or replace function new_axe_net.set_fund_fee_rule_enabled(
  p_rule_id bigint,
  p_enabled boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row new_axe_net.fund_fee_rules%rowtype;
  v_actor text;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.'
      using errcode = '42501';
  end if;

  select *
    into v_row
  from new_axe_net.fund_fee_rules
  where id = p_rule_id
  for update;

  if not found then
    raise exception '회비 규칙을 찾을 수 없습니다.'
      using errcode = '22023';
  end if;

  if v_row.source_key = 'base_weekly_fee'
     and p_enabled = false then
    raise exception '기본 fallback 회비 규칙은 비활성화할 수 없습니다.'
      using errcode = '22023';
  end if;

  if p_enabled = true and exists (
    select 1
    from new_axe_net.fund_fee_rules r
    where r.id <> p_rule_id
      and r.start_year = v_row.start_year
      and r.start_month = v_row.start_month
      and r.start_week = v_row.start_week
      and r.enabled = true
  ) then
    raise exception '동일 적용 시점에 다른 활성 회비 규칙이 있습니다.'
      using errcode = '23505';
  end if;

  update new_axe_net.fund_fee_rules
  set enabled = p_enabled
  where id = p_rule_id;

  v_actor := coalesce(
    new_axe_net.fund_actor_nickname(),
    'unknown'
  );

  insert into new_axe_net.fund_admin_audit_log (
    action,
    target_type,
    target_key,
    actor_user_id,
    actor_nickname,
    payload
  )
  values (
    case
      when p_enabled then 'enable_fee_rule'
      else 'disable_fee_rule'
    end,
    'fund_fee_rule',
    p_rule_id::text,
    auth.uid(),
    v_actor,
    jsonb_build_object(
      'start_year', v_row.start_year,
      'start_month', v_row.start_month,
      'start_week', v_row.start_week,
      'weekly_fee', v_row.weekly_fee,
      'enabled', p_enabled
    )
  );
end;
$$;

