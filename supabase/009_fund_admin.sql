create or replace function new_axe_net.create_fund_exemption(
  p_member_key text,
  p_year integer,
  p_month integer,
  p_week integer,
  p_reason text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_nickname text;
  v_actor text;
  v_source_key text;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.'
      using errcode = '42501';
  end if;

  if new_axe_net.fund_period_end(p_year, p_month, p_week) is null then
    raise exception '존재하지 않는 공금 주차입니다.'
      using errcode = '22023';
  end if;

  select m.nickname
    into v_nickname
  from new_axe_net.members m
  where m.member_key = p_member_key
    and m.status = 'active'
  limit 1;

  if v_nickname is null then
    raise exception '활동 중인 멤버를 찾을 수 없습니다.'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from new_axe_net.fund_exemptions e
    where e.member_key = p_member_key
      and e.year = p_year
      and e.month = p_month
      and e.week = p_week
      and e.enabled = true
  ) then
    raise exception '이미 해당 주차에 면제 등록된 멤버입니다.'
      using errcode = '23505';
  end if;

  v_actor := coalesce(
    new_axe_net.fund_actor_nickname(),
    'unknown'
  );

  v_source_key :=
    'new_fund_exemption:' ||
    floor(extract(epoch from clock_timestamp()) * 1000)::bigint::text ||
    ':' ||
    substr(
      md5(
        random()::text ||
        p_member_key ||
        clock_timestamp()::text
      ),
      1,
      10
    );

  insert into new_axe_net.fund_exemptions (
    member_key,
    nickname,
    year,
    month,
    week,
    exemption_type,
    reason,
    enabled,
    source_key,
    created_by
  )
  values (
    p_member_key,
    v_nickname,
    p_year,
    p_month,
    p_week,
    'manual',
    nullif(btrim(p_reason), ''),
    true,
    v_source_key,
    v_actor
  )
  returning id into v_id;

  insert into new_axe_net.fund_admin_audit_log (
    action,
    target_type,
    target_key,
    actor_user_id,
    actor_nickname,
    payload
  )
  values (
    'create_exemption',
    'fund_exemption',
    v_id::text,
    auth.uid(),
    v_actor,
    jsonb_build_object(
      'member_key', p_member_key,
      'nickname', v_nickname,
      'year', p_year,
      'month', p_month,
      'week', p_week,
      'reason', nullif(btrim(p_reason), '')
    )
  );

  return v_id;
end;
$$;

-- --------------------------------------------------
-- 면제 해제
-- 과거 기록은 삭제하지 않고 enabled=false로 보존
