create or replace function new_axe_net.disable_fund_exemption(
  p_exemption_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row new_axe_net.fund_exemptions%rowtype;
  v_actor text;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.'
      using errcode = '42501';
  end if;

  select *
    into v_row
  from new_axe_net.fund_exemptions
  where id = p_exemption_id
    and enabled = true
  for update;

  if not found then
    raise exception '활성 면제 기록을 찾을 수 없습니다.'
      using errcode = '22023';
  end if;

  update new_axe_net.fund_exemptions
  set enabled = false
  where id = p_exemption_id;

  v_actor := coalesce(
    new_axe_net.fund_actor_nickname(),
    'unknown'
  );

  insert into new_axe_net.fund_admin_audit_log (
    action,
    target_type,
    target_key,
    actor_user_id,
    actor_nickname,
    payload
  )
  values (
    'disable_exemption',
    'fund_exemption',
    p_exemption_id::text,
    auth.uid(),
    v_actor,
    jsonb_build_object(
      'member_key', v_row.member_key,
      'nickname', v_row.nickname,
      'year', v_row.year,
      'month', v_row.month,
      'week', v_row.week,
      'reason', v_row.reason
    )
  );
end;
$$;

