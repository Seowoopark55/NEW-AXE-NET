create table if not exists new_axe_net.fund_admin_audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  target_type text not null,
  target_key text,
  actor_user_id uuid,
  actor_nickname text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists fund_admin_audit_log_created_at_idx
on new_axe_net.fund_admin_audit_log (created_at desc);

alter table new_axe_net.fund_admin_audit_log enable row level security;

revoke all on table new_axe_net.fund_admin_audit_log
from anon, authenticated;

grant select on table new_axe_net.fund_admin_audit_log
to authenticated;

drop policy if exists "fund_admin_audit_read"
on new_axe_net.fund_admin_audit_log;

create policy "fund_admin_audit_read"
on new_axe_net.fund_admin_audit_log
for select
to authenticated
using (new_axe_net.is_admin());

create or replace function new_axe_net.fund_actor_nickname()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select m.nickname
  from new_axe_net.admin_accounts a
  join new_axe_net.members m
    on m.member_key = a.member_key
  where a.user_id = auth.uid()
    and a.enabled = true
  limit 1;
$$;

revoke all on function new_axe_net.fund_actor_nickname()
from public, anon;

grant execute on function new_axe_net.fund_actor_nickname()
to authenticated;

