-- 기간 목록: 공개 가능한 집계만 반환
create or replace function new_axe_net.get_fund_periods()
returns table (
  year integer,
  month integer,
  week integer,
  member_count bigint,
  completed_count bigint,
  unpaid_count bigint,
  exempt_count bigint,
  scheduled_count bigint,
  before_join_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    s.year,
    s.month,
    s.week,
    count(*) as member_count,
    count(*) filter (where s.status = '완료') as completed_count,
    count(*) filter (where s.status = '미납') as unpaid_count,
    count(*) filter (where s.status = '면제') as exempt_count,
    count(*) filter (where s.status = '예정') as scheduled_count,
    count(*) filter (where s.status = '가입 전') as before_join_count
  from new_axe_net.fund_status_snapshot s
  group by s.year, s.month, s.week
  order by s.year desc, s.month desc, s.week desc;
$$;

-- 선택 기간 요약 + 현재 전체 잔액
create or replace function new_axe_net.get_fund_summary(
  p_year integer default null,
  p_month integer default null,
  p_week integer default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_year integer;
  v_month integer;
  v_week integer;
  v_fee integer := 0;

  v_member_count bigint := 0;
  v_completed bigint := 0;
  v_unpaid bigint := 0;
  v_exempt bigint := 0;
  v_scheduled bigint := 0;
  v_before_join bigint := 0;

  v_expected bigint := 0;
  v_paid bigint := 0;
  v_unpaid_amount bigint := 0;
  v_exempt_amount bigint := 0;

  v_public_balance bigint := 0;
  v_company_balance bigint := 0;
begin
  if p_year is null or p_month is null or p_week is null then
    select p.year, p.month, p.week
      into v_year, v_month, v_week
    from (
      select
        s.year,
        s.month,
        s.week
      from new_axe_net.fund_status_snapshot s
      group by s.year, s.month, s.week
      having bool_or(s.status <> '예정')
      order by s.year desc, s.month desc, s.week desc
      limit 1
    ) p;
  else
    v_year := p_year;
    v_month := p_month;
    v_week := p_week;
  end if;

  if v_year is null then
    return jsonb_build_object(
      'period', null,
      'balance', jsonb_build_object('total', 0, 'public', 0, 'company', 0),
      'fee', 0,
      'counts', jsonb_build_object(),
      'amounts', jsonb_build_object()
    );
  end if;

  select r.weekly_fee
    into v_fee
  from new_axe_net.fund_fee_rules r
  where r.enabled = true
    and (r.start_year, r.start_month, r.start_week)
      <= (v_year, v_month, v_week)
  order by r.start_year desc, r.start_month desc, r.start_week desc, r.id desc
  limit 1;

  select
    count(*),
    count(*) filter (where s.status = '완료'),
    count(*) filter (where s.status = '미납'),
    count(*) filter (where s.status = '면제'),
    count(*) filter (where s.status = '예정'),
    count(*) filter (where s.status = '가입 전'),
    coalesce(sum(s.amount) filter (where s.status in ('완료', '미납')), 0),
    coalesce(sum(s.amount) filter (where s.status = '완료'), 0),
    coalesce(sum(s.amount) filter (where s.status = '미납'), 0),
    coalesce(sum(s.amount) filter (where s.status = '면제'), 0)
  into
    v_member_count,
    v_completed,
    v_unpaid,
    v_exempt,
    v_scheduled,
    v_before_join,
    v_expected,
    v_paid,
    v_unpaid_amount,
    v_exempt_amount
  from new_axe_net.fund_status_snapshot s
  where s.year = v_year
    and s.month = v_month
    and s.week = v_week;

  select
    coalesce(sum(
      case l.direction
        when '수입' then l.public_amount
        when '지출' then -l.public_amount
        when '조정' then l.public_amount
        else 0
      end
    ), 0),
    coalesce(sum(
      case l.direction
        when '수입' then l.company_amount
        when '지출' then -l.company_amount
        when '조정' then l.company_amount
        else 0
      end
    ), 0)
  into v_public_balance, v_company_balance
  from new_axe_net.fund_ledger l
  where l.status = 'active';

  return jsonb_build_object(
    'period', jsonb_build_object(
      'year', v_year,
      'month', v_month,
      'week', v_week
    ),
    'balance', jsonb_build_object(
      'total', v_public_balance + v_company_balance,
      'public', v_public_balance,
      'company', v_company_balance
    ),
    'fee', coalesce(v_fee, 0),
    'counts', jsonb_build_object(
      'members', v_member_count,
      'completed', v_completed,
      'unpaid', v_unpaid,
      'exempt', v_exempt,
      'scheduled', v_scheduled,
      'before_join', v_before_join
    ),
    'amounts', jsonb_build_object(
      'expected', v_expected,
      'paid', v_paid,
      'unpaid', v_unpaid_amount,
      'exempt', v_exempt_amount
    )
  );
end;
$$;

-- 선택 기간 멤버별 상태
create or replace function new_axe_net.get_fund_period_status(
  p_year integer,
  p_month integer,
  p_week integer
)
returns table (
  sort_order integer,
  nickname text,
  status text,
  amount integer,
  join_date date
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    m.sort_order,
    s.nickname,
    s.status,
    s.amount,
    s.join_date
  from new_axe_net.fund_status_snapshot s
  join new_axe_net.members m
    on m.member_key = s.member_key
  where s.year = p_year
    and s.month = p_month
    and s.week = p_week
  order by m.sort_order;
$$;

-- 공개 화면용 최근 원장: 메모/증빙 URL/내부키는 제외
create or replace function new_axe_net.get_fund_recent_ledger(
  p_limit integer default 12
)
returns table (
  ledger_date timestamptz,
  nickname text,
  ledger_type text,
  category text,
  direction text,
  account text,
  amount integer
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    l.ledger_date,
    l.nickname,
    l.ledger_type,
    l.category,
    l.direction,
    l.account,
    l.amount
  from new_axe_net.fund_ledger l
  where l.status = 'active'
  order by l.ledger_date desc, l.id desc
  limit least(greatest(coalesce(p_limit, 12), 1), 50);
$$;

