-- - 기존 fund_members는 NEW에서 별도 복제하지 않음:
--   현재 CSV 18명이 NEW members의 active 18명과 정확히 일치하므로 members를 기준으로 사용

create table if not exists new_axe_net.fund_fee_rules (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  source_id text,
  start_year integer not null,
  start_month integer not null check (start_month between 1 and 12),
  start_week integer not null check (start_week between 1 and 5),
  weekly_fee integer not null check (weekly_fee >= 0),
  note text,
  enabled boolean not null default true,
  source_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists new_axe_net.fund_exemptions (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  member_key text not null
    references new_axe_net.members(member_key)
    on delete cascade,
  nickname text,
  year integer not null,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 5),
  exemption_type text not null default 'manual',
  reason text,
  enabled boolean not null default true,
  source_key text not null unique,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists fund_exemptions_one_enabled_period_idx
on new_axe_net.fund_exemptions (member_key, year, month, week)
where enabled = true;

create table if not exists new_axe_net.fund_status_snapshot (
  id bigint generated by default as identity primary key,
  legacy_id bigint not null unique,
  member_key text not null
    references new_axe_net.members(member_key)
    on delete cascade,
  nickname text,
  year integer not null,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 5),
  status text not null
    check (status in ('가입 전', '미납', '완료', '면제', '예정')),
  amount integer not null default 0,
  join_date date,
  note text,
  updated_at timestamptz not null default now(),
  unique (member_key, year, month, week)
);

create index if not exists fund_status_snapshot_period_idx
on new_axe_net.fund_status_snapshot (year, month, week);

create table if not exists new_axe_net.fund_requests (
  id bigint generated by default as identity primary key,
  legacy_id bigint not null unique,
  guild_id text,
  discord_user_id text,
  discord_name text,
  member_key text not null
    references new_axe_net.members(member_key),
  nickname text,
  year integer not null,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 5),
  amount integer not null check (amount >= 0),
  status text not null
    check (status in ('approved', 'rejected', 'deleted')),
  evidence_url text,
  memo text,
  reviewer_discord_name text,
  reviewed_at timestamptz,
  source_key text not null unique,
  payment_mode text
    check (payment_mode is null or payment_mode in ('공용계좌', '회사잔고')),
  public_amount integer not null default 0,
  company_amount integer not null default 0,
  client_request_id text,
  sheet_request_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists fund_requests_period_member_idx
on new_axe_net.fund_requests (year, month, week, member_key);

create table if not exists new_axe_net.fund_ledger (
  id bigint generated by default as identity primary key,
  legacy_id bigint not null unique,
  member_key text
    references new_axe_net.members(member_key),
  nickname text,
  year integer,
  month integer check (month is null or month between 1 and 12),
  week integer check (week is null or week between 1 and 5),
  entry_type text not null
    check (entry_type in ('payment', 'adjustment', 'refund')),
  amount integer not null,
  public_amount integer not null default 0,
  company_amount integer not null default 0,
  status text not null
    check (status in ('active', 'cancelled')),
  approved_by_name text,
  approved_at timestamptz,
  legacy_request_key text,
  source_key text not null unique,
  memo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ledger_date timestamptz not null,
  ledger_type text not null,
  category text,
  direction text not null
    check (direction in ('수입', '지출', '조정')),
  account text not null
    check (account in ('공용계좌', '회사잔고')),
  evidence_url text,
  evidence_file_id text,
  operation_key text
);

create index if not exists fund_ledger_active_date_idx
on new_axe_net.fund_ledger (status, ledger_date desc);

create index if not exists fund_ledger_period_member_idx
on new_axe_net.fund_ledger (year, month, week, member_key);

