-- AXE NET v1.28.0
-- 026_assets_plika.sql
-- 회사자산 + 플리카 계좌 Supabase-native 전환
-- 전제: 001 ~ 025 적용 완료
--
-- 보안 기준
-- - 회사자산/반납내역: 관리자만 브라우저에서 조회/관리
-- - 플리카 계좌: anon 공개 금지. 일반 멤버는 Vercel member-session 서버를 통해 조회
-- - 플리카 신청: 일반 멤버는 member-session 서버가 service_role로 본인 신청만 등록
-- - 관리자 쓰기: Supabase Auth + is_admin() 검증 RPC
-- - 기존 public / Google Sheet는 런타임 경로로 사용하지 않음

create schema if not exists new_axe_net;
grant usage on schema new_axe_net to authenticated, service_role;

-- =========================================================
-- 1) 회사 자산
-- =========================================================

create table if not exists new_axe_net.company_assets (
  id bigint generated by default as identity primary key,
  legacy_no text,
  member_key text references new_axe_net.members(member_key) on update cascade on delete set null,
  owner_name text not null,
  asset_category text not null default '기타',
  asset_name text not null,
  acquisition_method text,
  acquired_at date,
  personal_cost bigint check (personal_cost is null or personal_cost >= 0),
  status text not null default '보유',
  note text,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists company_assets_active_status_idx
  on new_axe_net.company_assets (active, status, sort_order, id);
create index if not exists company_assets_owner_idx
  on new_axe_net.company_assets (owner_name, active);
create index if not exists company_assets_member_key_idx
  on new_axe_net.company_assets (member_key);

drop trigger if exists company_assets_touch_updated_at on new_axe_net.company_assets;
create trigger company_assets_touch_updated_at
before update on new_axe_net.company_assets
for each row execute function new_axe_net.touch_updated_at();

-- =========================================================
-- 2) 퇴사자 / 자산 반납 내역
-- =========================================================

create table if not exists new_axe_net.company_asset_returns (
  id bigint generated by default as identity primary key,
  legacy_no text,
  asset_id bigint references new_axe_net.company_assets(id) on update cascade on delete set null,
  member_key text references new_axe_net.members(member_key) on update cascade on delete set null,
  owner_name text not null,
  asset_name text not null,
  returned boolean not null default false,
  checker text,
  processed_at date,
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists company_asset_returns_active_returned_idx
  on new_axe_net.company_asset_returns (active, returned, processed_at desc, id desc);
create index if not exists company_asset_returns_member_key_idx
  on new_axe_net.company_asset_returns (member_key);

drop trigger if exists company_asset_returns_touch_updated_at on new_axe_net.company_asset_returns;
create trigger company_asset_returns_touch_updated_at
before update on new_axe_net.company_asset_returns
for each row execute function new_axe_net.touch_updated_at();

