create or replace function new_axe_net.save_company_asset(
  p_id bigint,
  p_legacy_no text,
  p_member_key text,
  p_owner_name text,
  p_asset_category text,
  p_asset_name text,
  p_acquisition_method text,
  p_acquired_at date,
  p_personal_cost bigint,
  p_status text,
  p_note text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_owner text := nullif(btrim(coalesce(p_owner_name,'')), '');
  v_asset text := nullif(btrim(coalesce(p_asset_name,'')), '');
  v_category text := coalesce(nullif(btrim(coalesce(p_asset_category,'')), ''), '기타');
  v_status text := coalesce(nullif(btrim(coalesce(p_status,'')), ''), '보유');
  v_order integer;
begin
  if not new_axe_net.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode='42501';
  end if;
  if v_owner is null or v_asset is null then
    raise exception '보유자와 자산명을 입력하세요.' using errcode='22023';
  end if;
  if p_personal_cost is not null and p_personal_cost < 0 then
    raise exception '개인 부담 비용은 0 이상이어야 합니다.' using errcode='22023';
  end if;
  if p_member_key is not null and not exists (
    select 1 from new_axe_net.members m where m.member_key = p_member_key
  ) then
    raise exception '연결할 멤버를 찾을 수 없습니다.' using errcode='22023';
  end if;

  if p_id is null then
    select coalesce(max(sort_order),0)+1 into v_order from new_axe_net.company_assets;
    insert into new_axe_net.company_assets (
      legacy_no,member_key,owner_name,asset_category,asset_name,acquisition_method,
      acquired_at,personal_cost,status,note,active,sort_order
    ) values (
      nullif(btrim(coalesce(p_legacy_no,'')),''),p_member_key,v_owner,v_category,v_asset,
      nullif(btrim(coalesce(p_acquisition_method,'')),''),p_acquired_at,p_personal_cost,v_status,
      nullif(btrim(coalesce(p_note,'')),''),true,v_order
    ) returning id into v_id;
  else
    update new_axe_net.company_assets
       set legacy_no = nullif(btrim(coalesce(p_legacy_no,'')),''),
           member_key = p_member_key,
           owner_name = v_owner,
           asset_category = v_category,
           asset_name = v_asset,
           acquisition_method = nullif(btrim(coalesce(p_acquisition_method,'')),''),
           acquired_at = p_acquired_at,
           personal_cost = p_personal_cost,
           status = v_status,
           note = nullif(btrim(coalesce(p_note,'')),''),
           active = true
     where id = p_id
     returning id into v_id;
    if v_id is null then raise exception '수정할 자산을 찾을 수 없습니다.' using errcode='P0002'; end if;
  end if;
  return v_id;
end;
$$;

create or replace function new_axe_net.deactivate_company_asset(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare v_count integer;
begin
  if not new_axe_net.is_admin() then raise exception '관리자 권한이 필요합니다.' using errcode='42501'; end if;
  update new_axe_net.company_assets set active=false where id=p_id and active=true;
  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;

create or replace function new_axe_net.save_company_asset_return(
  p_id bigint,
  p_legacy_no text,
  p_asset_id bigint,
  p_member_key text,
  p_owner_name text,
  p_asset_name text,
  p_returned boolean,
  p_checker text,
  p_processed_at date,
  p_note text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_owner text := nullif(btrim(coalesce(p_owner_name,'')), '');
  v_asset text := nullif(btrim(coalesce(p_asset_name,'')), '');
  v_checker text := nullif(btrim(coalesce(p_checker,'')), '');
begin
  if not new_axe_net.is_admin() then raise exception '관리자 권한이 필요합니다.' using errcode='42501'; end if;
  if v_owner is null or v_asset is null then raise exception '이름과 자산명을 입력하세요.' using errcode='22023'; end if;
  if p_asset_id is not null and not exists (select 1 from new_axe_net.company_assets a where a.id=p_asset_id) then
    raise exception '연결할 자산을 찾을 수 없습니다.' using errcode='22023';
  end if;
  if p_member_key is not null and not exists (select 1 from new_axe_net.members m where m.member_key=p_member_key) then
    raise exception '연결할 멤버를 찾을 수 없습니다.' using errcode='22023';
  end if;

  if coalesce(p_returned,false) and v_checker is null then
    v_checker := coalesce(new_axe_net.asset_actor_nickname(), 'ADMIN');
  end if;

  if p_id is null then
    insert into new_axe_net.company_asset_returns (
      legacy_no,asset_id,member_key,owner_name,asset_name,returned,checker,processed_at,note,active
    ) values (
      nullif(btrim(coalesce(p_legacy_no,'')),''),p_asset_id,p_member_key,v_owner,v_asset,
      coalesce(p_returned,false),v_checker,
      case when coalesce(p_returned,false) then coalesce(p_processed_at,(now() at time zone 'Asia/Seoul')::date) else p_processed_at end,
      nullif(btrim(coalesce(p_note,'')),''),true
    ) returning id into v_id;
  else
    update new_axe_net.company_asset_returns
       set legacy_no=nullif(btrim(coalesce(p_legacy_no,'')),''),
           asset_id=p_asset_id,
           member_key=p_member_key,
           owner_name=v_owner,
           asset_name=v_asset,
           returned=coalesce(p_returned,false),
           checker=v_checker,
           processed_at=case when coalesce(p_returned,false) then coalesce(p_processed_at,processed_at,(now() at time zone 'Asia/Seoul')::date) else p_processed_at end,
           note=nullif(btrim(coalesce(p_note,'')),''),
           active=true
     where id=p_id
     returning id into v_id;
    if v_id is null then raise exception '수정할 반납 내역을 찾을 수 없습니다.' using errcode='P0002'; end if;
  end if;
  return v_id;
end;
$$;

