create or replace function new_axe_net.save_member_account(
  p_member_key text,
  p_account text,
  p_enabled boolean default true,
  p_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_account text := nullif(btrim(coalesce(p_account,'')), '');
  v_order integer;
begin
  if not new_axe_net.is_admin() then raise exception '관리자 권한이 필요합니다.' using errcode='42501'; end if;
  if p_member_key is null or not exists (select 1 from new_axe_net.members m where m.member_key=p_member_key) then
    raise exception '멤버를 선택하세요.' using errcode='22023';
  end if;
  if v_account is null then raise exception '계좌번호를 입력하세요.' using errcode='22023'; end if;
  if length(v_account) > 100 then raise exception '계좌번호가 너무 깁니다.' using errcode='22023'; end if;

  select sort_order into v_order from new_axe_net.member_accounts where member_key=p_member_key;
  if v_order is null then select coalesce(max(sort_order),0)+1 into v_order from new_axe_net.member_accounts; end if;

  insert into new_axe_net.member_accounts (member_key,account,enabled,note,sort_order)
  values (p_member_key,v_account,coalesce(p_enabled,true),nullif(btrim(coalesce(p_note,'')),''),v_order)
  on conflict (member_key) do update
    set account=excluded.account,
        enabled=excluded.enabled,
        note=excluded.note
  returning id into v_id;
  return v_id;
end;
$$;

