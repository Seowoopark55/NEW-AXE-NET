create or replace function new_axe_net.review_member_account_request(
  p_request_id bigint,
  p_action text,
  p_review_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request new_axe_net.member_account_requests%rowtype;
  v_action text := lower(btrim(coalesce(p_action,'')));
  v_actor text;
  v_account_id bigint := null;
  v_order integer;
begin
  if not new_axe_net.is_admin() then raise exception '관리자 권한이 필요합니다.' using errcode='42501'; end if;
  if v_action not in ('approve','reject') then raise exception '승인 또는 반려 작업만 지원합니다.' using errcode='22023'; end if;

  select * into v_request from new_axe_net.member_account_requests where id=p_request_id for update;
  if not found then raise exception '신청 내역을 찾을 수 없습니다.' using errcode='P0002'; end if;
  if v_request.status <> 'pending' then raise exception '이미 처리된 신청입니다.' using errcode='22023'; end if;

  v_actor := coalesce(new_axe_net.asset_actor_nickname(),'ADMIN');

  if v_action='approve' then
    select sort_order into v_order from new_axe_net.member_accounts where member_key=v_request.member_key;
    if v_order is null then select coalesce(max(sort_order),0)+1 into v_order from new_axe_net.member_accounts; end if;

    insert into new_axe_net.member_accounts (member_key,account,enabled,note,sort_order)
    values (v_request.member_key,v_request.account,true,v_request.note,v_order)
    on conflict (member_key) do update
      set account=excluded.account, enabled=true, note=excluded.note
    returning id into v_account_id;

    update new_axe_net.member_account_requests
       set status='approved', reviewer=v_actor,
           review_note=nullif(btrim(coalesce(p_review_note,'')),''), reviewed_at=now()
     where id=p_request_id;
  else
    update new_axe_net.member_account_requests
       set status='rejected', reviewer=v_actor,
           review_note=nullif(btrim(coalesce(p_review_note,'')),''), reviewed_at=now()
     where id=p_request_id;
  end if;

  return coalesce(v_account_id,p_request_id);
end;
$$;

