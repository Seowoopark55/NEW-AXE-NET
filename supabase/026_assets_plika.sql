create or replace function new_axe_net.asset_actor_nickname()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select m.nickname
  from new_axe_net.admin_accounts a
  join new_axe_net.members m on m.member_key = a.member_key
  where a.user_id = auth.uid()
    and a.enabled = true
  limit 1;
$$;

revoke all on function new_axe_net.asset_actor_nickname() from public, anon;
grant execute on function new_axe_net.asset_actor_nickname() to authenticated;

