-- =========================================================
-- 4) 플리카 계좌 등록/변경 신청
-- =========================================================

create table if not exists new_axe_net.member_account_requests (
  id bigint generated by default as identity primary key,
  member_key text not null references new_axe_net.members(member_key) on update cascade on delete cascade,
  nickname text not null,
  account text not null,
  note text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  reviewer text,
  review_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists member_account_requests_pending_unique
  on new_axe_net.member_account_requests (member_key)
  where status = 'pending';
create index if not exists member_account_requests_status_created_idx
  on new_axe_net.member_account_requests (status, created_at desc);

drop trigger if exists member_account_requests_touch_updated_at on new_axe_net.member_account_requests;
create trigger member_account_requests_touch_updated_at
before update on new_axe_net.member_account_requests
for each row execute function new_axe_net.touch_updated_at();

