create or replace view new_axe_net.ai_knowledge_admin
with (security_invoker = true)
as
select
  k.id,
  k.domain,
  k.category,
  k.title,
  k.content,
  k.source_type,
  k.source_table,
  k.source_key,
  k.priority,
  k.active,
  k.embedding_model,
  k.embedding_status,
  k.embedding_error,
  k.embedded_at,
  k.created_by,
  k.updated_by,
  k.created_at,
  k.updated_at,
  coalesce(
    array_agg(a.alias order by a.alias)
      filter (where a.id is not null and a.active = true),
    array[]::text[]
  ) as aliases
from new_axe_net.ai_knowledge k
left join new_axe_net.ai_knowledge_aliases a
  on a.knowledge_id = k.id
group by k.id;

revoke all on new_axe_net.ai_knowledge_admin from public, anon;
