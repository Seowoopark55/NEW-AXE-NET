-- =========================================================
-- 6. updated_at / embedding 무효화
-- =========================================================
create or replace function new_axe_net.ai_knowledge_before_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();

  if
    new.title is distinct from old.title
    or new.content is distinct from old.content
    or new.domain is distinct from old.domain
    or new.category is distinct from old.category
  then
    new.embedding := null;
    new.embedding_model := null;
    new.embedding_status := 'pending';
    new.embedding_error := null;
    new.embedded_at := null;
  end if;

  return new;
end;
$$;

drop trigger if exists ai_knowledge_before_update_trigger
on new_axe_net.ai_knowledge;

create trigger ai_knowledge_before_update_trigger
before update on new_axe_net.ai_knowledge
for each row
execute function new_axe_net.ai_knowledge_before_update();

-- =========================================================
-- 7. 미답변 질문 누적 RPC
-- service_role/BOT에서 동일 질문을 반복 기록하면 ask_count만 증가합니다.
-- =========================================================
create or replace function new_axe_net.record_ai_unknown_question(
  p_question text,
  p_domain text default null,
  p_discord_user_id text default null,
  p_discord_nickname text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_question text := btrim(coalesce(p_question, ''));
  v_normalized text;
  v_id bigint;
begin
  if v_question = '' then
    raise exception '질문이 비어 있습니다.' using errcode = '22023';
  end if;

  v_normalized := new_axe_net.ai_normalize_text(v_question);
  if v_normalized = '' then
    raise exception '검색 가능한 질문이 아닙니다.' using errcode = '22023';
  end if;

  insert into new_axe_net.ai_unknown_questions (
    question,
    domain,
    first_user_id,
    first_nickname,
    ask_count,
    status,
    first_asked_at,
    last_asked_at
  )
  values (
    v_question,
    nullif(btrim(coalesce(p_domain, '')), ''),
    nullif(btrim(coalesce(p_discord_user_id, '')), ''),
    nullif(btrim(coalesce(p_discord_nickname, '')), ''),
    1,
    'open',
    now(),
    now()
  )
  on conflict (normalized_question)
  do update set
    question = excluded.question,
    domain = coalesce(excluded.domain, new_axe_net.ai_unknown_questions.domain),
    ask_count = new_axe_net.ai_unknown_questions.ask_count + 1,
    last_asked_at = now(),
    status = case
      when new_axe_net.ai_unknown_questions.status = 'ignored'
        then 'ignored'
      else 'open'
    end
  returning id into v_id;

  return v_id;
end;
$$;

revoke all on function new_axe_net.record_ai_unknown_question(text, text, text, text)
from public, anon, authenticated;

grant execute on function new_axe_net.record_ai_unknown_question(text, text, text, text)
to service_role;

-- =========================================================
-- 8. Hybrid Search RPC
-- keyword(trigram/exact) + semantic(vector cosine) 결합
-- embedding이 아직 없으면 keyword 검색만으로도 동작합니다.
-- =========================================================
create or replace function new_axe_net.search_ai_knowledge(
  p_query_text text,
  p_query_embedding extensions.vector(1536) default null,
  p_domain text default null,
  p_match_count integer default 8,
  p_min_score double precision default 0.20
)
returns table (
  knowledge_id bigint,
  domain text,
  category text,
  title text,
  content text,
  source_type text,
  source_table text,
  source_key text,
  priority integer,
  keyword_score double precision,
  semantic_score double precision,
  final_score double precision,
  matched_alias text
)
language sql
stable
security definer
set search_path = ''
as $$
  with input as (
    select
      btrim(coalesce(p_query_text, '')) as query_text,
      new_axe_net.ai_normalize_text(p_query_text) as query_norm,
      nullif(btrim(coalesce(p_domain, '')), '') as domain_filter,
      least(greatest(coalesce(p_match_count, 8), 1), 30) as result_limit
  ),
  candidates as (
    select
      k.id,
      k.domain,
      k.category,
      k.title,
      k.content,
      k.source_type,
      k.source_table,
      k.source_key,
      k.priority,

      greatest(
        case
          when new_axe_net.ai_normalize_text(k.title) = i.query_norm
            and i.query_norm <> ''
          then 1.0 else 0.0
        end,
        case
          when exists (
            select 1
            from new_axe_net.ai_knowledge_aliases a
            where a.knowledge_id = k.id
              and a.active = true
              and a.normalized_alias = i.query_norm
          )
          then 1.0 else 0.0
        end,
        extensions.similarity(lower(k.title), lower(i.query_text)),
        extensions.similarity(lower(k.content), lower(i.query_text)),
        coalesce((
          select max(extensions.similarity(lower(a.alias), lower(i.query_text)))
          from new_axe_net.ai_knowledge_aliases a
          where a.knowledge_id = k.id
            and a.active = true
        ), 0.0)
      )::double precision as keyword_score,

      case
        when p_query_embedding is not null and k.embedding is not null
        then greatest(0.0, 1.0 - (k.embedding OPERATOR(extensions.<=>) p_query_embedding))
        else 0.0
      end::double precision as semantic_score,

      (
        select a.alias
        from new_axe_net.ai_knowledge_aliases a
        where a.knowledge_id = k.id
          and a.active = true
        order by
          case when a.normalized_alias = i.query_norm then 0 else 1 end,
          extensions.similarity(lower(a.alias), lower(i.query_text)) desc,
          a.id
        limit 1
      ) as matched_alias

    from new_axe_net.ai_knowledge k
    cross join input i
    where k.active = true
      and (i.domain_filter is null or k.domain = i.domain_filter)
  ),
  scored as (
    select
      c.*,
      (
        case
          when p_query_embedding is not null
          then (c.semantic_score * 0.65) + (c.keyword_score * 0.35)
          else c.keyword_score
        end
        + least(greatest(c.priority, -100), 100) * 0.001
      )::double precision as final_score
    from candidates c
  )
  select
    s.id as knowledge_id,
    s.domain,
    s.category,
    s.title,
    s.content,
    s.source_type,
    s.source_table,
    s.source_key,
    s.priority,
    s.keyword_score,
    s.semantic_score,
    s.final_score,
    s.matched_alias
  from scored s
  cross join input i
  where s.final_score >= greatest(coalesce(p_min_score, 0.20), 0.0)
  order by s.final_score desc, s.priority desc, s.id desc
  limit least(greatest(coalesce(p_match_count, 8), 1), 30);
$$;

revoke all on function new_axe_net.search_ai_knowledge(
  text, extensions.vector, text, integer, double precision
) from public, anon, authenticated;

grant execute on function new_axe_net.search_ai_knowledge(
  text, extensions.vector, text, integer, double precision
) to service_role;

