-- =========================================================
-- 1. 공통 정규화 함수
-- =========================================================
create or replace function new_axe_net.ai_normalize_text(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(
    lower(coalesce(p_value, '')),
    '[^0-9a-z가-힣]+',
    '',
    'g'
  );
$$;

revoke all on function new_axe_net.ai_normalize_text(text) from public, anon;
grant execute on function new_axe_net.ai_normalize_text(text)
to authenticated, service_role;

-- =========================================================
-- 2. AI 지식
-- =========================================================
create table if not exists new_axe_net.ai_knowledge (
  id bigint generated by default as identity primary key,

  domain text not null default 'general',
  category text,
  title text not null,
  content text not null,

  source_type text not null default 'manual'
    check (source_type in (
      'manual',
      'info',
      'fund',
      'member',
      'asset',
      'outlaw',
      'notice',
      'rules',
      'map',
      'community',
      'legacy'
    )),
  source_table text,
  source_key text,

  priority integer not null default 0,
  active boolean not null default true,

  -- embedding 생성은 BOT/서버가 담당합니다.
  embedding extensions.vector(1536),
  embedding_model text,
  embedding_status text not null default 'pending'
    check (embedding_status in ('pending', 'ready', 'error', 'disabled')),
  embedding_error text,
  embedded_at timestamptz,

  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint ai_knowledge_title_not_blank
    check (btrim(title) <> ''),
  constraint ai_knowledge_content_not_blank
    check (btrim(content) <> '')
);

create unique index if not exists ai_knowledge_source_unique
  on new_axe_net.ai_knowledge(source_type, source_table, source_key)
  where source_key is not null and btrim(source_key) <> '';

create index if not exists ai_knowledge_active_domain_idx
  on new_axe_net.ai_knowledge(active, domain, category);

create index if not exists ai_knowledge_updated_idx
  on new_axe_net.ai_knowledge(updated_at desc);

create index if not exists ai_knowledge_title_trgm_idx
  on new_axe_net.ai_knowledge
  using gin (lower(title) extensions.gin_trgm_ops);

create index if not exists ai_knowledge_content_trgm_idx
  on new_axe_net.ai_knowledge
  using gin (lower(content) extensions.gin_trgm_ops);

-- 데이터가 충분히 쌓인 뒤 vector index를 사용합니다.
-- HNSW는 빈 테이블에서도 생성 가능하며 이후 자동 유지됩니다.
create index if not exists ai_knowledge_embedding_hnsw_idx
  on new_axe_net.ai_knowledge
  using hnsw (embedding extensions.vector_cosine_ops)
  where embedding is not null;

