create schema if not exists new_axe_net;
grant usage on schema new_axe_net to authenticated, service_role;

-- =========================================================
-- 1) 현재 무법지대 통계
-- =========================================================

create table if not exists new_axe_net.outlaw_stats_current (
  id bigint generated by default as identity primary key,
  member_key text not null unique
    references new_axe_net.members(member_key)
    on update cascade on delete cascade,
  source_nickname text not null,
  discord_user_id text not null unique,
  total_kills integer not null default 0 check (total_kills >= 0),
  total_deaths integer not null default 0 check (total_deaths >= 0),
  kd numeric(10,2) generated always as (
    case
      when total_deaths = 0 then total_kills::numeric
      else round(total_kills::numeric / total_deaths::numeric, 2)
    end
  ) stored,
  last_message_id text,
  source_image_url text,
  source_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists outlaw_stats_current_rank_idx
  on new_axe_net.outlaw_stats_current
  (total_kills desc, kd desc, total_deaths asc);

create index if not exists outlaw_stats_current_updated_idx
  on new_axe_net.outlaw_stats_current (source_updated_at desc);

drop trigger if exists outlaw_stats_current_touch_updated_at
on new_axe_net.outlaw_stats_current;

create trigger outlaw_stats_current_touch_updated_at
before update on new_axe_net.outlaw_stats_current
for each row
execute function new_axe_net.touch_updated_at();


-- =========================================================
-- 2) 무법지대 통계 기록
-- =========================================================

create table if not exists new_axe_net.outlaw_stats_history (
  record_id text primary key,
  member_key text not null
    references new_axe_net.members(member_key)
    on update cascade on delete cascade,
  source_nickname text not null,
  total_kills integer not null check (total_kills >= 0),
  total_deaths integer not null check (total_deaths >= 0),
  kill_delta integer not null default 0 check (kill_delta >= 0),
  death_delta integer not null default 0 check (death_delta >= 0),
  delta_kd numeric(10,2) not null default 0,
  channel_id text,
  discord_user_id text,
  message_id text,
  source_image_url text,
  confidence numeric(5,2),
  status text not null default 'approved'
    check (status in ('approved','pending','rejected')),
  recorded_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists outlaw_stats_history_member_recorded_idx
  on new_axe_net.outlaw_stats_history (member_key, recorded_at desc);

create index if not exists outlaw_stats_history_recorded_idx
  on new_axe_net.outlaw_stats_history (recorded_at desc);

create unique index if not exists outlaw_stats_history_message_unique
  on new_axe_net.outlaw_stats_history (message_id)
  where message_id is not null;


