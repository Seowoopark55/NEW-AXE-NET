-- =========================================================
-- 4) 무법지대 공략 단계
-- =========================================================

create table if not exists new_axe_net.outlaw_guide_steps (
  id bigint generated by default as identity primary key,
  location_key text not null
    references new_axe_net.outlaw_guide_locations(location_key)
    on update cascade on delete cascade,
  route_group text not null default '기본 루트',
  step_no text not null,
  title text not null,
  content text,
  image text,
  video_url text,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (location_key, route_group, step_no)
);

create index if not exists outlaw_guide_steps_location_order_idx
  on new_axe_net.outlaw_guide_steps
